"""Generate docs/settings.md from settings.py.

    python deploy/gen_settings_docs.py            # write docs/settings.md
    python deploy/gen_settings_docs.py --check    # exit 1 when the file is stale

Why this exists: docs/settings.md claims to be generated by exactly this script,
but the script was never committed (it sat in .gitignore) - so the table drifted
(204 of 236 keys listed, removed keys still documented). Keeping the generator in
the repo makes the doc reproducible and the drift checkable in the test suite.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from settings import DEFAULT_SETTINGS          # noqa: E402

OUT = ROOT / "docs" / "settings.md"
SRC = ROOT / "settings.py"

HEADER = """# HiveMind Settings

Generated from `settings.py` (`DEFAULT_SETTINGS`) by
`python deploy/gen_settings_docs.py` - do not edit by hand; edit the default (and
its comment) in `settings.py`, then re-run the generator.

**{count} settings keys.**

| Key | Type | Default | Note |
|---|---|---|---|
"""


def _comments() -> dict[str, str]:
    """The trailing comment of every '"key": value,  # note' line."""
    out: dict[str, str] = {}
    for line in SRC.read_text(encoding="utf-8").splitlines():
        m = re.match(r'\s*"([a-z0-9_]+)":\s*[^#]*,\s*(?:#\s*(.*))?$', line)
        if m and m.group(2):
            out[m.group(1)] = m.group(2).strip()
    return out


def _cell(value: object) -> str:
    if isinstance(value, bool):
        return f"`{value}`"
    if isinstance(value, (int, float)):
        return f"`{value}`"
    if isinstance(value, str):
        s = value if len(value) <= 40 else value[:37] + "..."
        return "`" + s.replace("|", "\\|") + "`"
    if value is None:
        return "`None`"
    if isinstance(value, dict):
        return "`{...}`" if value else "`{}`"
    if isinstance(value, list):
        return f"`[{len(value)} items]`" if value else "`[]`"
    return f"`{type(value).__name__}`"


def render() -> str:
    comments = _comments()
    rows = []
    for key in sorted(DEFAULT_SETTINGS):
        value = DEFAULT_SETTINGS[key]
        kind = ("bool" if isinstance(value, bool) else
                "int" if isinstance(value, int) else
                "float" if isinstance(value, float) else
                "str" if isinstance(value, str) else
                "list" if isinstance(value, list) else
                "object" if isinstance(value, dict) else
                "null" if value is None else type(value).__name__)
        note = comments.get(key, "").replace("|", "\\|")
        rows.append(f"| `{key}` | {kind} | {_cell(value)} | {note} |")
    body = "\n".join(rows) + "\n"
    return HEADER.format(count=len(DEFAULT_SETTINGS)) + body


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when docs/settings.md is stale")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("[settings-docs] STALE - run: python deploy/gen_settings_docs.py")
            return 1
        print("[settings-docs] up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"[settings-docs] wrote {OUT.relative_to(ROOT)} "
          f"({len(DEFAULT_SETTINGS)} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
